import SwiftUI

struct ModularInfoView: View {
    let isDivision: Bool
    @Environment(\.dismiss) private var dismiss
    var body: some View {
        NavigationStack {
            ScrollView {
                VStack(alignment: .leading, spacing: 20) {
                    Text("Обращение и деление").font(.title2.weight(.semibold))
                    MathLine("a · x ≡ 1 (mod m)")
                    Text("Обратное число существует ровно тогда, когда НОД(a, m) = 1. Модуль должен быть больше 1. Сначала приводим входные числа по модулю и полностью проверяем НОД.")
                    Text("Сначала — деление пополам").font(.headline)
                    Text("При преобразовании рабочих строк деление на 2 выполняем раньше вычитания. Перед делением корректируем коэффициенты. В методе третьей строки сначала фиксируем подходящую под условие строку: добавляем её к третьей и обновляем условие, затем продолжаем преобразования. Нулевые строки не делим, а при достижении результата останавливаемся.")
                    Text("Отрицательные представители").font(.headline)
                    MathLine("141 ≡ −142 (mod 283)")
                    MathLine("(52 | −142) → (26 | −71)")
                    Text("При нечётном модуле нечётный коэффициент заменяем чётным представителем: выбираем чётный из остатка r и r − m. Уже чётный коэффициент сразу делим. При чётном модуле нужны полные коэффициенты: прибавляем представление нуля (0 | m | −a) или (0 | −m | a), затем делим все координаты строки. Из двух допустимых вариантов выбираем меньший модуль α; при равенстве — прибавление m.")
                    ForEach(ModularMethod.allCases.filter { $0 != .automatic && (isDivision || $0 != .direct) }) { method in
                        VStack(alignment: .leading, spacing: 8) {
                            Text(method.title).font(.headline)
                            Text(method.detail)
                        }
                    }
                    Text("Запись метода для модуля 2ᵏ").font(.headline)
                    Text("Сначала показываем полную матрицу с двумя нулевыми строками. Дальше записываем только изменяемую первую строку: нулевые строки остаются теми же. Её левый элемент записываем степенью двойки, вплоть до 2⁰. Номера строк в обозначениях операций сохраняются.")
                    Text("Обозначения преобразований").font(.headline)
                    TransformationLabel(operation: "Mᵢ(½)")
                    Text("Разделить строку i пополам.")
                    TransformationLabel(operation: "Mᵢ,ⱼ(t)")
                    Text("К строке i прибавить строку j, умноженную на t. Каждая матрица показывает состояние после указанной операции. В полной записи число = α·a + β·m; в сокращённой — число ≡ α·a (mod m).")
                    Text("В бинарных преобразованиях модуль целого множителя строки не превышает 2; вычитание обозначается коэффициентом −1. Исключение — добавление к третьей строке при делении по модулю: если левый элемент рабочей строки равен 1 или 2, разрешён любой нужный целый множитель.")
                    if isDivision {
                        MathLine("(u / v) mod m = (u · v⁻¹) mod m")
                        Text("Третья строка изначально нулевая. Под каждой матрицей пишем условие: левый элемент рабочей строки должен быть не больше несобранной части числителя. Проверяем исходную матрицу и результат каждого деления или вычитания. Подходящую строку сразу прибавляем к третьей, затем обновляем условие: числитель минус левый элемент третьей строки. После добавления продолжаем преобразования рабочих строк с приоритетом деления пополам. Для строк с левым элементом больше 2 добавляем одну копию за шаг; для 1 или 2 можно добавить сразу нужное число копий. При условии ≤ 0 числитель собран. Взаимную простоту знаменателя и модуля проверяем заранее.")
                        MathLine("104 ≤ 153; 153 − 104 = 49")
                        MathLine("26 ≤ 49; 153 − 130 = 23")
                        MathLine("13 ≤ 23; 153 − 143 = 10")
                    }
                    Text("Если НОД не равен 1").font(.headline)
                    Text("Обратного элемента нет. Для дроби отдельно сообщаем, имеет ли соответствующее сравнение решения, но не называем один из них значением дроби: деление через обратный элемент здесь не определено.")
                }.font(.callout).padding(22)
            }.background(AppStyle.background)
                .navigationTitle("Об алгоритмах").navigationBarTitleDisplayMode(.inline)
                .toolbar { ToolbarItem(placement: .confirmationAction) { Button("Готово") { dismiss() }.accessibilityIdentifier("closeAlgorithm") } }
        }.presentationDetents([.large]).presentationDragIndicator(.visible)
    }
}
