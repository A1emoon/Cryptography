        case .factor: "Множитель многочлена f — многочлен h, для которого f = h·k. Если h — собственный нетривиальный множитель, то 0 < deg h < deg f: он не является ни константой, ни всем f. Только такой множитель действительно разделяет задачу на две меньшие."
        case .multiplicity: "Кратность корня r — число повторений множителя x−r. Например, в x³(x−1)² корень 0 имеет кратность 3, а 1 — кратность 2. Для решения сравнения каждый корень записывается один раз; повторения не создают новых классов решений."
        case .fermat: "Малая теорема Ферма: для простого q ненулевой остаток a в степени q − 1 равен 1. Поэтому все ненулевые элементы поля являются корнями многочлена Ферма. Нулевой корень проверяют отдельно; многочлен, содержащий все остатки поля, получают вычитанием x из его степени с показателем q."
        case .euclid: "Чтобы найти НОД многочленов, делят первый на второй с остатком, затем второй на найденный остаток и продолжают. Степень остатка на каждом шаге уменьшается. Последний ненулевой остаток, приведённый к старшему коэффициенту 1, и есть НОД. Равенство (a,b) = (b,a−b·h) сохраняет общие делители."
        case .horner: "Схема Горнера вычисляет значение многочлена без отдельного нахождения каждой степени: ((aₙx + aₙ₋₁)x + …)x + a₀. После каждого умножения и сложения можно брать остаток по q. Это даёт независимую проверку найденного корня."
        }
    }
}
struct MathExplainedText: View {
    let text: String
    var excluded: MathTerm? = nil
    @State private var selected: MathTerm?
    private var attributed: AttributedString {
        var result = AttributedString(text)
        for term in MathTerm.allCases where term != excluded {
            guard let regex = try? NSRegularExpression(pattern: "\\b(?:" + term.pattern + ")\\b", options: [.caseInsensitive]) else { continue }
            for match in regex.matches(in: text, range: NSRange(text.startIndex..., in: text)) {
                guard let range = Range(match.range, in: text), let lower = AttributedString.Index(range.lowerBound, within: result),
                      let upper = AttributedString.Index(range.upperBound, within: result),
                      result[lower..<upper].runs.allSatisfy({ $0.link == nil }) else { continue }
                result[lower..<upper].link = URL(string: "math-term://definition/" + term.rawValue)
            }
        }
        return result
    }
    var body: some View {
        Text(attributed).font(.callout).tint(AppStyle.accent)
            .environment(\.openURL, OpenURLAction { url in
                guard url.scheme == "math-term", let term = MathTerm(rawValue: url.lastPathComponent) else { return .systemAction }
                selected = term; return .handled
            }).sheet(item: $selected) { MathDefinitionView(term: $0) }
    }
}
struct MathDefinitionView: View {
    let term: MathTerm
    var body: some View {
        StudentDetailSheet(title: term.title) {
            MathExplainedText(text: term.definition, excluded: term)
            ForEach(term.formulas.indices, id: \.self) { StudentFormulaView(atoms: term.formulas[$0]) }
        }
    }
}
struct MathTermLinks: View {
    let terms: [MathTerm]
    var identifierPrefix = "rabinTerm_"
    @State private var selected: MathTerm?
    var body: some View {
        NotebookFlow(spacing: 12) {
            ForEach(terms) { term in
                Button(term.title) { selected = term }.font(.callout).underline()
                    .accessibilityIdentifier(identifierPrefix + term.rawValue)
            }
        }.sheet(item: $selected) { MathDefinitionView(term: $0) }
    }
}

extension MathTerm {
    var formulas: [[StudentMathAtom]] {
        switch self {
        case .reciprocity:
            [[.symbol("u", "v"), .text("="), .fractionPower("(−1)", "(u − 1)(v − 1)", "4"), .symbol("v", "u")]]
        case .euler:
            [[.fractionPower("a", "p − 1", "2"), .text("≡"), .symbol("a", "p"), .text("(mod p)")]]
        case .conjugate:
            [[.text("(u + vω)(u − vω) = u² − v²d")]]
        case .quadraticResidue:
            [[.fractionPower("a", "q − 1", "2"), .text("≡ 1 или −1 (mod q)")]]
        case .fermat:
            [[.power("a", "q − 1"), .text("≡ 1 (mod q), a ≢ 0")], [.power("x", "q"), .text("− x")]]
        case .congruence:
            [[.text("a ≡ b (mod q)"), .text("⇔"), .text("q ∣ (a − b)")]]
        case .equivalent:
            [[.text("f(x) ≡ 0"), .text("⇔"), .text("u·f(x) ≡ 0, u ≢ 0")]]
        case .residueClass:
            [[.text("x ≡ r (mod q)"), .text("⇔"), .text("x = r + kq, k ∈ ℤ")]]
        default: []
        }
    }
}
